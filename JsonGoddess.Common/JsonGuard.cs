using System;

namespace JsonGoddess
{
    /// <summary>
    /// Стражи чтения (§6.3 плана): за что хост может попросить отказ вместо
    /// молчаливого принятия.
    ///
    /// Ось ортогональна <c>JsonFeature</c> (§6.2, ещё не сделан):
    /// <c>JsonFeature</c> отвечает «понимать ли эту конструкцию», а
    /// <c>JsonGuard</c> - «отказать ли, потому что RFC 8259 или сам
    /// <c>System.Text.Json</c> с опциями по умолчанию её запрещают». Поэтому
    /// это два разных перечисления, а не одно.
    ///
    /// Значения читаются генератором из аргумента конструктора
    /// <see cref="JsonGuardAttribute"/> числом (см. <c>JsonGoddess.Generator.Model.JsonGuard</c> -
    /// битовая раскладка обязана совпасть один в один, иначе связывание
    /// атрибута на чужой сборке даст не те флаги).
    /// </summary>
    [Flags]
    public enum JsonGuard
    {
        None = 0,

        /// <summary>
        /// Два свойства с одним именем в одном объекте - отказ, а не «второе
        /// значение побеждает». Пробой подтверждено: по умолчанию
        /// <c>System.Text.Json</c> дубликаты разрешает (последнее значение
        /// побеждает - ровно как у нас без стража), но
        /// <c>JsonSerializerOptions.AllowDuplicateProperties = false</c>
        /// отказывает <c>JsonException</c> - и только на дубликате
        /// сопоставленного члена: повтор незнакомого имени эталон пропускает
        /// не глядя, и страж делает то же самое.
        /// </summary>
        DuplicateProperties = 1 << 0,

        /// <summary>
        /// Мусор после верхнеуровневого значения (не считая пробелов) - отказ.
        /// Пробой подтверждено: у эталона это встроенное и безусловное
        /// поведение перегрузок <c>string</c>/<c>ReadOnlySpan&lt;byte&gt;</c> -
        /// способа его выключить у самого эталона нет, а у нас по умолчанию
        /// хвост документа никто не проверяет вовсе.
        /// </summary>
        TrailingContent = 1 << 1,

        /// <summary>
        /// Неэкранированный управляющий символ (&lt; U+0020) внутри строки
        /// (RFC 8259 §7) - отказ. Пробой подтверждено: эталон отказывает
        /// всегда, без опции - в <c>JsonReaderOptions</c> нет свойства, которое
        /// бы это разрешало. Здесь тем не менее сделано opt-in: цена
        /// более широкого поиска (34-значный набор вместо двухзначного
        /// <c>IndexOfAny</c>) не измерена, а измерять её - работа человека,
        /// не эмиттера.
        /// </summary>
        ControlCharsInStrings = 1 << 2,

        /// <summary>
        /// Числа вне грамматики RFC 8259 §6 - <c>01</c>, <c>+1</c>, <c>.5</c>,
        /// <c>1.</c>, <c>1e</c> - отказ. Пробой подтверждено: эталон отказывает
        /// всегда и без опции, а <c>Utf8Parser</c>, на который опирается наш
        /// разбор по умолчанию, эту грамматику не проверяет вовсе.
        /// </summary>
        StrictNumbers = 1 << 3,

        /// <summary>
        /// Битая UTF-8-последовательность в строковом значении или ключе
        /// словаря, либо непарный <c>\uD800</c>-суррогат в escape'е (строки
        /// или экранированного имени свойства) - отказ. Пробой подтверждено:
        /// эталон при материализации в <see cref="string"/> отказывает всегда
        /// (<c>InvalidOperationException</c>: "Cannot transcode invalid UTF-8
        /// JSON text to UTF-16 string" / "...missing low surrogate"), тогда
        /// как наш декодер по умолчанию использует лёгкий
        /// <see cref="System.Text.Encoding.UTF8"/> и молча подставляет U+FFFD.
        /// </summary>
        InvalidUtf8 = 1 << 4,

        /// <summary>
        /// Вложенность глубже настроенного предела (см.
        /// <see cref="JsonGuardAttribute.MaxDepth"/>, умолчание 64 - как у
        /// эталона). Пробой подтверждено: 64 вложенных массива читаются, 65 -
        /// отказ и у <c>System.Text.Json</c> с опциями по умолчанию, причём
        /// предел считается и по известным членам, и по пропускаемым
        /// поддеревьям неизвестных свойств. У нас без стража глубина не
        /// считается вовсе.
        /// </summary>
        MaxDepth = 1 << 5,

        /// <summary>
        /// Свойство, не сопоставленное ни одному члену, - отказ вместо
        /// пропуска поддерева. Аналог
        /// <c>JsonUnmappedMemberHandling.Disallow</c>; пробой подтверждено,
        /// что у эталона это решение снимается на уровне всего графа типов
        /// одного сериализатора (как и здесь - решение на хосте, а не на
        /// отдельном субъекте).
        /// </summary>
        UnknownProperties = 1 << 6,

        /// <summary>
        /// Композит: всё вышеперечисленное. То же поведение, которое получает
        /// документ, обслуженный <c>System.Text.Json</c> с опциями по
        /// умолчанию, - без затрат на хосте, который не просил ничего из
        /// этого.
        /// </summary>
        SystemTextJsonCompatible = DuplicateProperties
            | TrailingContent
            | ControlCharsInStrings
            | StrictNumbers
            | InvalidUtf8
            | MaxDepth
            | UnknownProperties,
    }
}

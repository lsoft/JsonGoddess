namespace JsonGoddess.Compat.Interop
{
    /// <summary>
    /// Под какое поведение напечатан код.
    ///
    /// <para>
    /// Профиль - это не настройка, а <b>снимок</b>: имена свойств
    /// преобразуются на компиляции, диспетчер имён печатается тогда же, и
    /// подменить их в рантайме нечем. Поэтому вариантов ровно столько, сколько
    /// генератор напечатал, и резолвер не настраивает код под опции, а выбирает
    /// из напечатанного.
    /// </para>
    /// </summary>
    public enum BridgeProfile
    {
        /// <summary>
        /// Умолчания эталона: имена как объявлены, регистр значим, число
        /// только числом.
        /// </summary>
        Default = 0,

        /// <summary>
        /// <c>JsonSerializerDefaults.Web</c> - то, что строят ASP.NET Core MVC
        /// и minimal API: camelCase, имена без учёта регистра, число можно
        /// строкой.
        ///
        /// <para>
        /// <c>MaxDepth</c> в профиль не входит, хотя MVC его и выставляет (32).
        /// Мосту он не нужен: глубину, как и всю прочую лексику, проверяет сам
        /// <c>Utf8JsonReader</c>, созданный эталоном по его же опциям. Войди
        /// он в профиль - пришлось бы держать два веб-варианта, MVC'шный и
        /// minimal-API'шный, ради ограничения, которое мы и так соблюдаем
        /// чужими руками.
        /// </para>
        /// </summary>
        Web = 1,
    }
}

using System;

namespace JsonGoddess
{
    /// <summary>
    /// Opt-in фичи чтения (и, для одного флага, записи) - §6.2 плана.
    ///
    /// Ось ортогональна <see cref="JsonGuard"/>: <c>JsonGuard</c> отвечает
    /// «отказать ли, потому что RFC 8259 или сам <c>System.Text.Json</c> с
    /// опциями по умолчанию её запрещают», а <c>JsonFeature</c> - «понимать ли
    /// эту конструкцию сверх того, что понимает читатель по умолчанию».
    /// Читатель по умолчанию строг к тому, чего RFC не разрешает (комментарии,
    /// висячие запятые, число строкой) - опустив это, включённый флаг
    /// <b>расширяет</b> приём, а не сужает его, как это делает страж.
    ///
    /// Устройство то же самое, что у <see cref="JsonGuard"/>: выключенная
    /// фича не стоит ни одной ветки в порождённом коде - эмиттер выбирает,
    /// какой из двух вариантов кода печатать, на этапе генерации, а не какой
    /// из двух исполнить в рантайме. Значения читаются генератором из
    /// аргумента конструктора <see cref="JsonFeatureAttribute"/> числом (см.
    /// <c>JsonGoddess.Generator.Model.JsonFeature</c> - битовая раскладка
    /// обязана совпасть один в один).
    ///
    /// Из семи строк исходной таблицы §6.2 заведено пять: шестая
    /// (<c>SurrogateGuard</c>) не заведена вовсе - пробой (см.
    /// <c>docs/opt-in-json-features.md</c>) показал, что наш дефолт на записи
    /// уже совпадает с дефолтом эталона, и заводить флаг, который ничего не
    /// меняет, значило бы завести флаг ради флага.
    /// </summary>
    [Flags]
    public enum JsonFeature
    {
        None = 0,

        /// <summary>
        /// <c>//</c> и <c>/* */</c> между токенами (JSONC), кроме одного
        /// места - пробой подтвердил, что сам эталон
        /// (<c>JsonSerializerOptions.ReadCommentHandling = Skip</c>) не
        /// принимает комментарий между именем свойства и двоеточием
        /// (<c>{"Id" /* c */ : 1}</c> - отказ), хотя везде вокруг этого места
        /// комментарий легален. Подробности и полный перечень проверенных
        /// позиций - <c>docs/opt-in-json-features.md</c> §1.
        /// </summary>
        Comments = 1 << 0,

        /// <summary>
        /// Одна лишняя запятая перед закрывающей скобкой - <c>[1,2,]</c>,
        /// <c>{"a":1,}</c>. Не более одной и не вместо элемента: <c>[,]</c>,
        /// <c>[,1]</c>, <c>[1,,2]</c> эталон отвергает даже с
        /// <c>AllowTrailingCommas = true</c> - пробоем подтверждено.
        /// </summary>
        TrailingCommas = 1 << 1,

        /// <summary>
        /// <c>"NaN"</c>, <c>"Infinity"</c>, <c>"-Infinity"</c> как строки на
        /// месте <see cref="float"/>/<see cref="double"/> (аналог
        /// <c>JsonNumberHandling.AllowNamedFloatingPointLiterals</c>). Матч
        /// точный (регистро-зависимый: <c>"nan"</c> и <c>"+Infinity"</c>
        /// эталон отвергает, проверено пробой), и только для
        /// <see cref="float"/>/<see cref="double"/> - <see cref="decimal"/> не
        /// умеет ни то, ни другое ни у эталона, ни у нас.
        ///
        /// Флаг двусторонний: на <b>записи</b> тоже - без него <c>NaN</c>
        /// и бесконечности не имеют JSON-формы и это отказ (как у эталона,
        /// пробоем подтверждено - оба бросают <see cref="ArgumentException"/>
        /// уже без всякой фичи); с флагом они пишутся той же строкой.
        /// </summary>
        NamedFloatingPointLiterals = 1 << 2,

        /// <summary>
        /// Число в кавычках там, где ждётся число - аналог
        /// <c>JsonNumberHandling.AllowReadingFromString</c>. Пробоем
        /// подтверждено: ведущий ноль и ведущий плюс внутри строки эталон
        /// принимает (<c>"01"</c>, <c>"+1"</c>), а окружающий пробел,
        /// пустую строку и <c>null</c> - нет. Наш разбор и без фичи не
        /// проверяет грамматику (то же основание, что у <c>StrictNumbers</c>),
        /// поэтому переиспользование обычного парсера числа автоматически
        /// даёт то же самое послабление.
        /// </summary>
        NumbersFromStrings = 1 << 3,

        /// <summary>
        /// Регистронезависимый матч имён свойств (аналог
        /// <c>JsonSerializerOptions.PropertyNameCaseInsensitive</c>).
        ///
        /// Заведён <b>частично</b>, и это не недоделка, а решение вопроса O5
        /// (§15 плана): сворачивание регистра здесь - по ASCII (см.
        /// <c>JsonAsciiName</c>), а у эталона - по Unicode (пробоем
        /// подтверждено: он сворачивает и кириллицу). На ASCII-имени оба
        /// совпадения совпадают буква в букву; на не-ASCII они разошлись бы
        /// молча, что запрещено принципом 1 - поэтому такой тип честно
        /// отвергается на компиляции, а не обслуживается приблизительно.
        /// Второй отказ - на паре членов, чьи имена совпадают после
        /// ASCII-свёртки (эталон в этом случае тоже отказывает, но в рантайме
        /// при первом обращении; здесь - на компиляции, раньше и понятнее).
        /// </summary>
        CaseInsensitiveNames = 1 << 4,

        /// <summary>
        /// Композит: всё вышеперечисленное разом.
        /// </summary>
        SystemTextJsonCompatible = Comments
            | TrailingCommas
            | NamedFloatingPointLiterals
            | NumbersFromStrings
            | CaseInsensitiveNames,
    }
}

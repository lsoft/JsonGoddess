using JsonGoddess.PerformanceTests.Model;

namespace JsonGoddess.PerformanceTests.Bridge
{
    /// <summary>
    /// Единственный вызов фасада во всём проекте - и он здесь не ради работы,
    /// а ради того, чтобы генератор узнал, какие типы обслуживать.
    ///
    /// <para>
    /// У маршрута A списка <c>[JsonSubject]</c> нет по построению: он находит
    /// типы сам, обходя аргументы найденных вызовов фасада. Мост печатается
    /// тем же связывателем и по тому же списку, поэтому без единого вызова не
    /// появилось бы ни того ни другого.
    /// </para>
    ///
    /// <para>
    /// <c>Order[]</c> отдельно не якорится: массив - не именованный тип, и
    /// связыватель его пропускает. Так и надо. В замере массив принадлежит
    /// эталону, а мост отвечает за каждый элемент - ровно та форма, в которой
    /// веб-метод возвращает список.
    /// </para>
    /// </summary>
    internal static class BridgeAnchor
    {
        internal static byte[] Anchor(Order order)
        {
            return Compat.JsonSerializer.SerializeToUtf8Bytes(order);
        }
    }
}

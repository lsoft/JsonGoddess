using System;

namespace JsonGoddess.Compat
{
    /// <summary>
    /// Метка на тех перегрузках фасада, у которых быстрый путь есть.
    ///
    /// <para>
    /// Нужна генератору: перехватывать он обязан <b>не</b> всякий вызов
    /// <c>Serialize</c>/<c>Deserialize</c> с известным <c>T</c>, а только тот,
    /// где связка <see cref="CompatBinding{T}"/> будет спрошена. Из ста трёх
    /// методов таких восемь; у остальных <c>T</c> тоже известен, но работа
    /// уходит эталону безусловно - и порождать для них код значило бы печатать
    /// заведомо мёртвый, а на несвязавшемся типе ещё и выдавать <c>JGD001</c>
    /// про вызов, которому быстрый путь всё равно не достался бы.
    /// </para>
    ///
    /// <para>
    /// Метка живёт здесь, а не списком имён в генераторе, по той же причине, по
    /// которой обход графа живёт рядом с <c>TryBind</c>: два списка,
    /// разъехавшись, дают не отказ, а тихое расхождение. Добавили быстрый путь
    /// новой перегрузке - поставили метку, и генератор узнал об этом из того же
    /// файла, где это случилось.
    /// </para>
    /// </summary>
    [AttributeUsage(AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
    public sealed class CompatFastPathAttribute : Attribute
    {
    }
}

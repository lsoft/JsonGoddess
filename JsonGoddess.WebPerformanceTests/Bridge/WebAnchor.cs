using JsonGoddess.PerformanceTests.Model;

namespace JsonGoddess.WebPerformanceTests.Bridge
{
    /// <summary>
    /// Единственный вызов фасада во всём проекте - и он здесь не ради работы,
    /// а ради того, чтобы генератор узнал, какие типы обслуживать.
    ///
    /// <para>
    /// Связыватель находит типы сам, обходя аргументы найденных вызовов
    /// фасада, и оба варианта моста - умолчательный и веб - печатаются по
    /// этому же списку. Без единого вызова не появилось бы ни одного, и
    /// лестница мерила бы эталон против эталона.
    /// </para>
    ///
    /// <para>
    /// <c>Order[]</c> отдельно не якорится: массив - не именованный тип, и
    /// связыватель его пропускает. Так и надо. В ответе веб-метода массивом
    /// владеет эталон, а мост отвечает за каждый элемент - ровно та форма,
    /// которую лестница и меряет.
    /// </para>
    /// </summary>
    internal static class WebAnchor
    {
        internal static byte[] Anchor(Order order)
        {
            return Compat.JsonSerializer.SerializeToUtf8Bytes(order);
        }
    }
}

namespace JsonGoddess
{
    /// <summary>
    /// К чему привязано смещение отказа. Путь (§6.4) строится обратным
    /// проходом по документу до этого смещения, и одно и то же число значит
    /// разное в зависимости от того, кто отказал: сканер споткнулся <b>на</b>
    /// байте, инжектор отказался от лексемы, которая на этом байте
    /// <b>кончилась</b>, а проверка обязательных членов недовольна
    /// <b>объектом</b>, который этим байтом закрылся.
    ///
    /// Без этого различия путь врёт на один сегмент: у
    /// <c>{"orders":[{"id":1},{}]}</c> с необъявленным обязательным членом
    /// отказ приходится на закрывающую скобку второго элемента, и проход,
    /// принявший её за успешно дочитанную, назовёт <c>$.orders[2]</c> -
    /// элемент, которого в документе нет.
    /// </summary>
    public enum JsonPathAnchor
    {
        /// <summary>
        /// Смещение - это байт, на котором сканер отказал. Всё, что начиналось
        /// до него, дочитано.
        /// </summary>
        AtByte = 0,

        /// <summary>
        /// Смещение - конец лексемы, которую отказался разбирать инжектор
        /// (<see cref="System.FormatException"/>). Сама лексема дочитанной не
        /// считается: путь обязан назвать член, в который её не удалось
        /// уложить.
        /// </summary>
        AfterToken = 1,

        /// <summary>
        /// Смещение - конец объекта, к которому отказ относится целиком: не
        /// пришёл обязательный член. Закрывающая скобка дочитанной не
        /// считается (иначе объект уже закрыт и назвать его нечем), а
        /// незавершённое имя свойства внутри него сбрасывается: виноват
        /// объект, а не последний из его членов.
        /// </summary>
        EnclosingObject = 2,
    }
}
